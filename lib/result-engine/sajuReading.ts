export function getPersonalityReading(element: ElementKey, seed: string): PersonalityReading {
  const t = TEMPERAMENT_BANK[element];
  const r = RELATIONSHIP_BANK[element];
  const g = GROWTH_BANK[element];
  return {
    temperament: t[pickVariant(`${seed}-temperament`, t.length)],
    relationships: r[pickVariant(`${seed}-relationships`, r.length)],
    growth: g[pickVariant(`${seed}-growth`, g.length)],
  };
}

