export interface BalanceInsight {
  strongElement: ElementKey;
  strongText: string;
  weakElement: ElementKey | null;
  weakText: string;
}

export function getBalanceInsight(distribution: Record<ElementKey, number>): BalanceInsight {
  const sorted = ELEMENT_ORDER.map((key) => [key, distribution[key]] as const).sort((a, b) => b[1] - a[1]);
  const strongElement = sorted[0][0];
  const weakest = sorted[sorted.length - 1];
  const isNotablyWeak = weakest[1] === 0 || weakest[1] < sorted[0][1];
  const weakElement = isNotablyWeak ? weakest[0] : null;

  return {
    strongElement,
    strongText: STRONG_INSIGHT[strongElement],
    weakElement,
    weakText: weakElement
      ? WEAK_INSIGHT[weakElement]
      : "오행이 고루 갖춰져 있어서 특별히 부족한 기운은 없어요. 균형이 잘 잡힌 사주예요.",
  };
}

