export function getCategoryBlurb(slug: CategorySlug, element: ElementKey, seed: string): string {
  const bank = FORTUNE_CATEGORIES[slug].blurbs?.[element];
  if (!bank || bank.length === 0) return "";
  return bank[pickVariant(seed, bank.length)];
}
